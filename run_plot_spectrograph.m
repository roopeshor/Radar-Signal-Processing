%%% Testing stacked spectrogram plotter using VisPy (sp_py)

filepath = fullfile("Data" , "rain", "EXP_DBS_CH4_28Jun2026_14_28_16");
disp("Processing file: " + filepath);

obs = Observation(filepath, add_mmts=false, add_uvw=false);
obs = obs.compute_spectra_with(@mccf.compute_spectra);
obs = obs.apply_fx(@simple.HS_denoise_beam);

data = obs.north.denoised_spectra;
plt.plot_doppler_spectra(...
	spectra=data, ...
	heights=obs.heights, ...
	x_axis_type="doppler", ...
	x_max=obs.velocities(end) ...
	)
plt.save_stacked_spectrogram(...
	(data), ...
	obs.heights, obs.velocities, ...
	plot_gradiated    = true,     ...
	plot_add_colorbar = true,     ...
	plot_color        = 'parula', ...
	plot_thick        = 0.5,       ...
	peak_marker       = "white.", ...
	marker_size       = 0,        ...
	amplitude_scale   = .9,       ...
	ref_line_thick    = 0,       ...
	ref_line_color    = "red",    ...
	export_path       = 'plots/28Jun2026_14_28_16-north-raw.png', ...
	export_dpi        = 700 ...
	);
