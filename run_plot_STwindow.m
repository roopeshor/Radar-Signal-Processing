filepath = fullfile("Data", "other", "EXP_DBS_CH4_29Jul2026_16_16_17");
disp("Processing file: " + filepath);

obs = getObservation(filepath);
obs = apply_beam_fx(obs, @mccf.compute_all_params, win_coeff=1.5);
N = obs.north;

figure("Name", "ST Window");
i1 = 1;
i2 = obs.nRangeBins;
vl = [-obs.v_max, obs.v_max]/3;
vidx = round(rescale(vl, 1, 1024, InputMin=-obs.v_max, InputMax=obs.v_max));
M = rescale(N.a_params.peaks_idx, -obs.v_max, obs.v_max, InputMax=1024, InputMin=1);

heights = obs.heights(i1:i2)/1000;
dspec = N.denoised_spectra(i1:i2, vidx(1):vidx(2));
spec = N.spectra(i1:i2, vidx(1):vidx(2));
compm = M(i1:i2);
refm = N.ref_M1(i1:i2) * obs.DBS_Factor;
stw = N.a_params.mccf_ST_W(i1:i2, :);

plt.plot_doppler_spectra(...
	spectra    = 20*log10(abs(spec)), ...
	heights    = heights,             ...
	x_max      = vl(2)               ...
	)
clim([-135, 0])
figure()
plt.plot_doppler_spectra(...
	spectra    = 20*log10(abs(dspec)), ...
	comp_m     = -compm,               ...
	ref_m      = -refm,                ...
	heights    = heights,             ...
	x_max      = vl(2)               ...
	)
clim([-135, 0])
figure()
plt.plot_doppler_spectra(...
	spectra    = 20*log10(abs(dspec(10:60, :))), ...
	comp_m     = -compm(10:60),               ...
	ref_m      = -refm(10:60),                ...
	heights    = heights(10:60),             ...
	x_max      = vl(2)               ...
	)
clim([-135, 0])
colorbar;
plt.plot_ST_window(stw, obs.v_max, heights, "white")
